def get_preset_abi(preset_name: str) -> List[Dict[str, Any]]:
    """Return the ABI list for a recognized preset name."""
    key = str(preset_name).strip().lower()
    if key not in ABI_PRESETS:
        known = ", ".join(sorted(ABI_PRESETS.keys()))
        raise ValueError(f"Unknown ABI preset {preset_name!r}. Supported: {known}.")
    return ABI_PRESETS[key]
